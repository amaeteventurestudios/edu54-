// Differential privacy for LLMs (phase 18, lesson 22): an invented clinic network fine-tunes a notes assistant on patient records. DP-SGD
// clips each example's gradient to a radius C, sums them and adds Gaussian noise scaled to C, so no single record can move the model much.
// The scene shows six per-example gradients (one an unusual record), the clipping ring and the noisy sum. A toy accountant turns the noise
// multiplier into epsilon; extraction of planted records and task quality are illustrative curves. Returning raw confidence scores and
// auditing with random canaries are the two ways the guarantee is misread.
const C = 0.6;
const GRADS = [[0.5, 15], [0.46, 45], [0.54, 75], [0.48, 105], [0.44, 135], [0.95, 300]];
function model(o) {
  const s = o.sigma;
  const eps = !o.clip || s < 0.05 ? Infinity : 4 / s;
  const extract = o.clip ? 30 * Math.exp(-1.6 * s) : 30 * Math.exp(-0.3 * s);
  const quality = 80 - 4 * s - 3 * s * s;
  const audit = o.strong ? extract : extract * 0.2;
  return { eps, extract, quality, audit };
}

